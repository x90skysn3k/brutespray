func mustParseFile(t *testing.T, name string) map[Host]int {
	t.Helper()
	hosts, err := ParseFile(name)
	if err != nil {
		t.Fatalf("ParseFile(%s): %v", name, err)
	}
	return hosts
}

func requireHost(t *testing.T, hosts map[Host]int, h Host) {
	t.Helper()
	if _, ok := hosts[h]; !ok {
		t.Errorf("missing host %+v in %v", h, hosts)
	}
}

func requireNoHost(t *testing.T, hosts map[Host]int, h Host) {
	t.Helper()
	if _, ok := hosts[h]; ok {
		t.Errorf("unexpected host %+v in %v", h, hosts)
	}
}

func TestParseFileMasscanOJ(t *testing.T) {
	hosts := mustParseFile(t, "testdata/masscan_oj.json")

	// open ports with known mappings survive; closed and unmapped drop out
	requireHost(t, hosts, Host{Service: "https", Host: "203.0.113.10", Port: 443})
	requireHost(t, hosts, Host{Service: "ssh", Host: "10.0.0.5", Port: 22})
	if len(hosts) != 2 {
		t.Errorf("expected 2 hosts, got %d: %v", len(hosts), hosts)
	}
}

