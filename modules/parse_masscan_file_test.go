func TestParseFileEmpty(t *testing.T) {
	path := filepath.Join(t.TempDir(), "empty.json")
	if err := os.WriteFile(path, nil, 0o600); err != nil {
		t.Fatal(err)
	}
	if _, err := ParseFile(path); err == nil {
		t.Fatal("expected error for empty file")
	}
}

func TestParseFileListWithComments(t *testing.T) {
	dir := t.TempDir()
	path := filepath.Join(dir, "targets.list")
	contents := "# generated by script\n# keep this header\n\nssh:10.0.0.1:22\n"
	if err := os.WriteFile(path, []byte(contents), 0o600); err != nil {
		t.Fatal(err)
	}
	hosts := mustParseFile(t, path)
	requireHost(t, hosts, Host{Service: "ssh", Host: "10.0.0.1", Port: 22})
	if len(hosts) != 1 {
		t.Errorf("expected 1 host, got %d: %v", len(hosts), hosts)
	}
}

func TestDetectStreamMasscanList(t *testing.T) {
	in := "#masscan\nopen tcp 443 203.0.113.10 1786719582\nopen tcp 22 10.0.0.5 1786719583\n"
	format, err := DetectStreamFormat(strings.NewReader(in))
	if err != nil {
		t.Fatalf("DetectStreamFormat: %v", err)
	}
	if format != "masscan-list" {
		t.Fatalf("format = %q, want masscan-list", format)
	}
	hosts, err := ParseStream(strings.NewReader(in))
	if err != nil {
		t.Fatalf("ParseStream: %v", err)
	}
	if len(hosts) != 2 || hosts[0].Service != "https" || hosts[1].Service != "ssh" {
		t.Fatalf("masscan-list stream parse failed: %+v", hosts)
	}
}

func TestDetectStreamSkipsCommentLines(t *testing.T) {
	in := "# a comment header\n10.0.0.5:22\n"
	format, err := DetectStreamFormat(strings.NewReader(in))
	if err != nil {
		t.Fatalf("DetectStreamFormat: %v", err)
	}
	if format != "naabu" {
		t.Fatalf("format = %q, want naabu", format)
	}
}

func TestDefaultServiceForPortDeterministicSharedPorts(t *testing.T) {
	// Ports shared by a stable and a beta descriptor must resolve to the
	// canonical stable service regardless of map iteration order.
	for _, c := range []struct {
		port int
		want string
	}{
		{25, "smtp"},
		{80, "http"},
		{443, "https"},
	} {
		for range 50 {
			if got := defaultServiceForPort(c.port); got != c.want {
				t.Fatalf("defaultServiceForPort(%d) = %q, want %q", c.port, got, c.want)
			}
		}
	}
}
